"""Generate data/qa_operators.tsv: the default outfit of every QA operator ("cha_" item).

QA keeps no operator -> parts table of its own: a character's parts live in its cloud-stored
character loadout (qa3333 0x2E16E50 + 76 n, filled from the online service), so an offline
server has to supply them. Each operator <code> wears, per part category, the first marketplace
part (in id order) whose name is <cat>_<code>... or, failing that, one of whose
mp/coCharItems/<cat>.csv models is named <cat>_<code>... (fja_viper wears fja_ELIveteranA_sc_f).
A missing body part or head (fpa, fja, han, hea) is the first part of the operator's gender:
hea_socomb for a man, hea_chung for a woman. Operators without any
part are written as comments. The file is plain TSV and meant to be edited by hand.

Every coCharItems variant is tagged gender (m f, s = any), faction (tf sc zm, ss = any) and skin
(wht yel blk cau, sss = any), and the client draws a part only in a variant that covers the
player's tags (qa3333 0x40C980). The skin column is therefore the first of wht yel blk cau that
every part of the outfit has: hea_chung exists only in yel, so its wearer has to be yel.

usage: py -3 tools/data/gen_qa_operators.py   (reads and writes under data/)
"""
import csv
import pathlib

CATEGORIES = ["fpa", "boo", "fja", "han", "hea", "ves", "heg", "elp", "knp", "eye", "bar"]
SKINS = ["wht", "yel", "blk", "cau"]  # client field 19 order (qa3333 off_CE4880)
BODY = ["fpa", "fja", "han", "hea"]  # never left empty: the first part of the operator's gender stands in
DATA = pathlib.Path(__file__).resolve().parents[2] / "data"
TABLES = DATA / "tables"


def read_csv(path):
    with open(path, encoding="latin-1", newline="") as f:
        return [row for row in csv.reader(f) if row]


def main():
    items = [r for r in read_csv(TABLES / "mp_coMarketplaceItems.csv") if r[0].isdigit() and len(r) > 3]
    items.sort(key=lambda r: int(r[0]))
    parts = {c: [r[1] for r in items if r[2] == "cat" and r[3].lower() == c] for c in CATEGORIES}
    models, genders, tags = {}, {}, {}
    for c in CATEGORIES:
        path = TABLES / f"mp_coCharItems_{c}.csv"
        if not path.exists():
            continue
        for row in read_csv(path):
            if len(row) < 4:
                continue
            name = row[0].lower()
            models.setdefault(name, []).append(row[3].lower())
            genders.setdefault(name, row[2][:1])
            if row[1] == "model" and len(row[2].split()) == 3:
                tags.setdefault(name, []).append(row[2].split())

    def skins_of(part, gender):
        """the skins some variant of `part` for `gender` is drawn in (all four for an untagged part)"""
        variants = [t for t in tags.get(part.lower(), []) if t[0] in (gender, "s")]
        if not variants:
            return set(SKINS)
        return set().union(*(SKINS if t[2] == "sss" else [t[2]] for t in variants))

    lines = ["# operator\tgender\tskin\t" + "\t".join(CATEGORIES),
             "# generated by tools/gen_qa_operators.py; gender m/f, skin wht/yel/blk/cau, - = no part"]
    for op in (r[1] for r in items if r[1].lower().startswith("cha_")):
        code = op[4:].lower()
        outfit = {}
        for c in CATEGORIES:
            prefix = f"{c}_{code}"
            named = [p for p in parts[c] if p.lower().startswith(prefix)]
            modelled = [p for p in parts[c] if any(m.startswith(prefix) for m in models.get(p.lower(), []))]
            if named or modelled:
                outfit[c] = (named or modelled)[0]
        if not outfit:
            lines.append(f"# {op}: no parts")
            continue
        order = ["fja", "fpa", "han", "hea"] + CATEGORIES
        gender = next((genders[outfit[c].lower()] for c in order if c in outfit and outfit[c].lower() in genders), "m")
        for c in BODY:
            if c not in outfit:
                outfit[c] = next((p for p in parts[c] if genders.get(p.lower()) == gender), "-")
        worn = [p for p in outfit.values() if p != "-"]
        common = set(SKINS).intersection(*(skins_of(p, gender) for p in worn))
        if not common:
            common = skins_of(outfit["hea"], gender) if outfit.get("hea", "-") != "-" else set(SKINS)
            print(f"warning: {op}: no skin fits every part; using the head's")
        skin = next(s for s in SKINS if s in common)
        lines.append("\t".join([op, gender, skin] + [outfit.get(c, "-") for c in CATEGORIES]))
    (DATA / "qa_operators.tsv").write_text("\n".join(lines) + "\n", encoding="ascii")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
